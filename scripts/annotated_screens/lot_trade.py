"""Block-style annotated mock-ups for lot / trade screens (SC-03-01, SC-03-05, SC-04-01, SC-05-02).

Each element: (no, x, y, w, h, kind, text). no = wireframe item number (string) or "" for frame parts.
kind: frame | box | field | button | primary | table | dialog | label | banner
"""
from PIL import Image, ImageDraw

from .common import font as f

STYLE = {
    "frame": ("#f3f4f6", "#9ca3af", 1),
    "box": ("#ffffff", "#374151", 2),
    "field": ("#ffffff", "#6b7280", 1),
    "button": ("#e5e7eb", "#374151", 2),
    "primary": ("#1d4ed8", "#1e3a8a", 2),
    "table": ("#ffffff", "#374151", 1),
    "dialog": ("#fffbeb", "#b45309", 2),
    "label": ("#ffffff", "#d1d5db", 1),
    "banner": ("#fee2e2", "#b91c1c", 1),
}


def draw_screen(title, size, elements, out_path, note):
    w, h = size
    img = Image.new("RGB", (w, h + 40), "#ffffff")
    d = ImageDraw.Draw(img)
    for no, x, y, ew, eh, kind, text in elements:
        fill, outline, width = STYLE[kind]
        if kind == "dialog":
            d.rectangle([x, y, x + ew, y + eh], fill=fill)
            # dashed outline
            for i in range(x, x + ew, 12):
                d.line([i, y, min(i + 6, x + ew), y], fill=outline, width=2)
                d.line([i, y + eh, min(i + 6, x + ew), y + eh], fill=outline, width=2)
            for j in range(y, y + eh, 12):
                d.line([x, j, x, min(j + 6, y + eh)], fill=outline, width=2)
                d.line([x + ew, j, x + ew, min(j + 6, y + eh)], fill=outline, width=2)
        else:
            d.rectangle([x, y, x + ew, y + eh], fill=fill, outline=outline, width=width)
        color = "#ffffff" if kind == "primary" else "#111827"
        if kind == "frame":
            color = "#6b7280"
        size_px = 15 if kind in ("table", "frame", "label") else 17
        d.multiline_text((x + (22 if no else 10), y + 6), text, font=f(size_px, kind in ("primary", "button")),
                         fill=color, spacing=6)
        if no:
            r = 15 if len(no) <= 2 else 19
            cx, cy = x + 2, y + 2
            d.ellipse([cx - r, cy - r, cx + r, cy + r], fill="#dc2626", outline="#ffffff", width=2)
            tw = d.textlength(no, font=f(15, True))
            d.text((cx - tw / 2, cy - 11), no, font=f(15, True), fill="#ffffff")
    d.rectangle([0, h, w, h + 40], fill="#111827")
    d.text((12, h + 9), f"{title}  —  {note}", font=f(15), fill="#ffffff")
    img.save(out_path)


